import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { installUniAppLifecycle, appEntrySnapshot } from '../../src/adapters/uniapp.js'
import { dispatchAutoTrack } from '../../autotrack.js'
import { mountAutoTrackSfc } from '../support/autotrack-fixture.js'
import { miniHost, miniTargets } from '../support/miniprogram-host.js'
import type { TrackerRuntime } from '../../src/core/growingIO.js'
import type { AppRequestApi } from '../../src/platform/uni.js'
import type { AutoTrackCall } from '../../src/plugins/gioEventAutoTracking/contract.js'

beforeEach(() => {
  vi.useFakeTimers()
  vi.setSystemTime(1_000_000)
  vi.spyOn(console, 'info').mockImplementation(() => undefined)
})
afterEach(() => { vi.clearAllTimers(); vi.useRealTimers(); vi.unstubAllGlobals() })

describe.each(miniTargets)('%s complete runtime', target => {
  it('builds mini wire events, persists only identity and sequence, and starts a fresh session after restart', async () => {
    const f = miniHost(target)
    expect(f.init()).toBe(true)
    expect(await f.tracker.whenReady()).toBe(true)
    f.show()
    expect(f.tracker.track('purchase', { value: 0 })).toBe(true)
    f.tracker.setUserId('user-a')
    f.tracker.setUserAttributes({ role: 'member' })
    const events = f.tracker.queuedEvents()
    expect(events.map(event => event.eventType)).toEqual(['VISIT', 'PAGE', 'CUSTOM', 'LOGIN_USER_ATTRIBUTES'])
    expect(events[0]).toMatchObject({ query: 'entry=1', referralPage: 'external-app', appChannel: 'scn:1001' })
    expect(events[1]).toMatchObject({ query: 'page=1', referralPage: 'external-app', title: '首页' })
    expect(events[2]).toMatchObject({ query: 'page=1', attributes: { value: '0' }, title: '首页' })
    expect(events.every(event => event.domain === f.appId && event.platform === (target === 'mp-weixin' ? 'MinP' : 'alip'))).toBe(true)
    expect(events.every(event => !('appState' in event) && !('appName' in event) && !('orientation' in event))).toBe(true)
    for (let index = 0; index < 10; index++) await Promise.resolve()
    const keys = [...f.values.keys()]
    expect(keys).toHaveLength(2)
    expect(keys.every(key => key.startsWith(`gio:mp:v1:${target}:`) && (key.endsWith(':identity') || key.endsWith(':meta')))).toBe(true)
    expect(f.host.getStorageSync.mock.calls.every(([key]) => !key.endsWith(':session') && !key.includes(':queue'))).toBe(true)
    expect([...f.values.values()].join(' ')).not.toContain('user-a')
    const next = f.create()
    expect(next.init({ accountId: 'account', dataSourceId: 'source', appId: f.appId })).toBe(true)
    await next.whenReady()
    expect(next.queuedEvents()).toHaveLength(0)
    next.onAppLaunch({ path: 'pages/home', query: '', scene: '1001' })
    next.onAppShow({ path: 'pages/home', query: '', scene: '1001' })
    expect(next.queuedEvents()[0]).toMatchObject({ deviceId: events[0]!.deviceId, userId: 'user-a', eventSequenceId: 4 })
    expect(next.queuedEvents()[0]!.sessionId).not.toBe(events[0]!.sessionId)
  })
  it.each([299999, 300000, 300001])('uses the five-minute background boundary at %s ms', async gap => {
    const f = miniHost(target); f.init(); await f.tracker.whenReady(); f.show()
    f.tracker.onPageHide('home-1')
    f.tracker.onAppHide()
    const first = f.sent.find(event => event.eventType === 'VISIT')!
    vi.setSystemTime(Date.now() + gap)
    f.tracker.onAppShow({ path: 'pages/home', query: 'fresh=1', scene: '1001' })
    f.tracker.onPageShow('home-1', '首页')
    const all = [...f.sent, ...f.tracker.queuedEvents()]
    const visits = all.filter(event => event.eventType === 'VISIT')
    expect(visits).toHaveLength(gap > 300000 ? 2 : 1)
    const page = all.filter(event => event.eventType === 'PAGE').at(-1)!
    expect(page.sessionId === first.sessionId).toBe(gap <= 300000)
    if (gap > 300000) expect(visits.at(-1)!.query).toBe('fresh=1')
  })
  it('freezes an entry within a visit, renews on scene change and avoids a duplicate Page.onShow', async () => {
    const f = miniHost(target); f.init(); await f.tracker.whenReady(); f.show()
    f.tracker.onAppHide()
    f.tracker.onAppShow({ path: 'other', query: 'ignored=1', scene: '1001' })
    f.tracker.setUserId('a'); f.tracker.setUserId('b')
    expect(f.tracker.queuedEvents().filter(event => event.eventType === 'VISIT').at(-1)!.query).toBe('entry=1')
    const before = f.tracker.queuedEvents().length
    f.tracker.onAppShow({ path: 'new-entry', query: 'fresh=1', scene: '1002', referralPage: 'fresh-app' })
    const added = f.tracker.queuedEvents().slice(before)
    expect(added.map(event => event.eventType)).toEqual(['VISIT', 'PAGE'])
    expect(added[0]).toMatchObject({ path: 'new-entry', query: 'fresh=1', referralPage: 'fresh-app', appChannel: 'scn:1002' })
    expect(added[1]!.sessionId).toBe(added[0]!.sessionId)
    f.tracker.onPageShow('home-1', 'New title')
    expect(f.tracker.queuedEvents().length).toBe(before + 2)
    f.tracker.onPageHide('home-1'); f.tracker.onPageShow('home-1', 'New title')
    expect(f.tracker.queuedEvents().length).toBe(before + 3)
  })
  it('handles Page.onShow before App.onShow and clears hidden or unloaded pending pages', async () => {
    const f = miniHost(target); f.init(); await f.tracker.whenReady()
    f.tracker.onPageLoad({ instanceId: 'home', route: 'pages/home', query: '', referralPage: null })
    f.tracker.onPageShow('home', '首页')
    f.tracker.onAppShow({ path: 'pages/home', query: '', scene: '1001', referralPage: 'external' })
    expect(f.tracker.queuedEvents().map(event => event.eventType)).toEqual(['VISIT', 'PAGE'])
    expect(f.tracker.queuedEvents()[1]!.referralPage).toBe('external')
    f.tracker.onAppHide()
    f.tracker.onPageShow('home', '首页'); f.tracker.onPageHide('home')
    f.tracker.onPageShow('home', '首页'); f.tracker.onPageUnload('home')
    f.tracker.onAppShow({ path: 'pages/home', query: '', scene: '1002' })
    expect(f.tracker.queuedEvents().map(event => event.eventType)).toEqual(['VISIT'])
    expect(f.tracker.onPageShow(1 as unknown as string, null)).toBe(false)
  })
  it('renews before an event after explicit activity expiry, including the equality boundary', async () => {
    const f = miniHost(target); f.init({ sessionExpires: 1 }); await f.tracker.whenReady(); f.show()
    vi.setSystemTime(Date.now() + 60000)
    f.tracker.track('at_boundary')
    expect(f.tracker.queuedEvents().filter(event => event.eventType === 'VISIT')).toHaveLength(1)
    vi.setSystemTime(Date.now() + 60001)
    f.tracker.track('expired')
    const events = f.tracker.queuedEvents().slice(-3)
    expect(events.map(event => event.eventType)).toEqual(['VISIT', 'PAGE', 'CUSTOM'])
    expect(new Set(events.map(event => event.sessionId)).size).toBe(1)
    vi.setSystemTime(Date.now() + 60001)
    f.tracker.onAppShow({ path: 'pages/home', query: '', scene: '1001' })
    expect(f.tracker.queuedEvents().slice(-2).map(event => event.eventType)).toEqual(['VISIT', 'PAGE'])
  })
  it('defers early events, keeps the initial consent boundary and resumes with fresh page context', async () => {
    const f = miniHost(target); f.init({ dataCollect: false }); f.show()
    const read = vi.fn(() => 'secret')
    expect(f.tracker.track('denied', { get value() { return read() } })).toBe(false)
    await f.tracker.whenReady()
    expect(read).not.toHaveBeenCalled()
    expect(f.tracker.queuedEvents()).toHaveLength(0)
    f.tracker.setDataCollect(true)
    expect(f.tracker.queuedEvents().map(event => event.eventType)).toEqual(['VISIT', 'PAGE'])
    f.tracker.track('accepted')
    f.tracker.setDataCollect(false)
    expect(f.tracker.track('denied_again')).toBe(false)
    f.tracker.setDataCollect(true)
    expect(f.tracker.queuedEvents().slice(-2).map(event => event.eventType)).toEqual(['VISIT', 'PAGE'])
    const early = miniHost(target); early.init(); early.tracker.track('before_show')
    await early.tracker.whenReady(); early.show()
    expect(early.tracker.queuedEvents().slice(0, 2).map(event => event.eventType)).toEqual(['VISIT', 'CUSTOM'])
  })
  it('coalesces a burst and flushes immediately on hide without a duplicate close or delayed resend', async () => {
    const f = miniHost(target); f.init(); await f.tracker.whenReady(); f.show()
    for (let index = 0; index < 100; index++) f.tracker.track('burst', { index })
    expect(f.host.request).not.toHaveBeenCalled()
    await vi.advanceTimersByTimeAsync(999)
    expect(f.host.request).not.toHaveBeenCalled()
    await vi.advanceTimersByTimeAsync(1)
    expect(f.host.request).toHaveBeenCalledTimes(3)
    expect(f.sent).toHaveLength(102)
    expect(f.sent.every(event => !('requestId' in event))).toBe(true)
    f.tracker.track('pending')
    f.tracker.onAppHide(); f.tracker.onAppHide()
    expect(f.sent.slice(-2).map(event => event.eventType)).toEqual(['CUSTOM', 'APP_CLOSED'])
    const count = f.host.request.mock.calls.length
    await vi.advanceTimersByTimeAsync(1000)
    expect(f.host.request).toHaveBeenCalledTimes(count)
  })
  it('uses the same finite retry and single-settlement rules when mini callbacks are late or duplicated', async () => {
    const f = miniHost(target)
    const callbacks: Array<Parameters<AppRequestApi['request']>[0]> = []
    f.host.request.mockImplementation(options => { callbacks.push(options); return { abort: vi.fn() } })
    f.init(); await f.tracker.whenReady(); f.show()
    await vi.advanceTimersByTimeAsync(1000)
    callbacks[0]!.fail({ errMsg: 'request:fail timeout' })
    callbacks[0]!.success({ statusCode: 204 })
    await vi.advanceTimersByTimeAsync(2000)
    expect(callbacks).toHaveLength(2)
    callbacks[1]!.success({ statusCode: 204 }); callbacks[1]!.fail({ errMsg: 'late' })
    expect(f.tracker.queuedEvents()).toHaveLength(0)
    f.tracker.track('bad_request')
    await vi.advanceTimersByTimeAsync(1000)
    callbacks[2]!.success({ statusCode: 400 })
    await vi.advanceTimersByTimeAsync(10000)
    expect(callbacks).toHaveLength(3)
    expect(f.tracker.queuedEvents()).toHaveLength(0)
  })
  it('runs compiled event listeners through the mini protocol while preserving privacy and business calls', async () => {
    vi.stubGlobal('__GIO_AUTOTRACK_VERIFICATION__', true)
    const f = miniHost(target)
    f.tracker.registerPlugins({ name: 'gioEventAutoTracking' })
    f.init(); await f.tracker.whenReady(); f.show()
    const business = vi.fn(event => event)
    const fixture = mountAutoTrackSfc('<script setup>import { business } from "fixture"</script><template><button id="save" @tap="business($event)"/><input data-growing-track @blur="business($event)"/><input password data-growing-track @blur="business($event)"/></template>', (probe, event) => dispatchAutoTrack(probe as AutoTrackCall, event), { fixture: { business } })
    try {
      const native = { type: 'tap', timeStamp: 1, currentTarget: { id: 'save', dataset: {} }, target: { id: 'save', dataset: {} } }
      fixture.fire(0, 'onTap', native)
      fixture.fire(0, 'onTap', native)
      fixture.fire(0, 'onBlur', { type: 'blur', timeStamp: 2, currentTarget: { dataset: { growingTrack: true } }, detail: { value: 'allowed' } })
      fixture.fire(1, 'onBlur', { type: 'blur', timeStamp: 3, currentTarget: { dataset: { growingTrack: true } }, detail: { value: 'secret' } })
      expect(business).toHaveBeenCalledTimes(4)
      const views = f.tracker.queuedEvents().filter(event => String(event.eventType).startsWith('VIEW_'))
      expect(views.map(event => event.eventType)).toEqual(['VIEW_CLICK', 'VIEW_CHANGE'])
      expect(views[0]!.xpath).toBe('save#business')
      expect(views[1]!.textValue).toBe('allowed')
      expect(JSON.stringify(f.tracker.queuedEvents())).not.toContain('secret')
    } finally { fixture.unmount() }
  })
  it('installs only explicit App and Page hooks, uses native routes and does not mistake a component for App', async () => {
    const f = miniHost(target); f.init(); await f.tracker.whenReady()
    const mixin = vi.fn()
    installUniAppLifecycle({ mixin }, f.tracker, { miniprogram: target, host: f.host })
    const hooks = mixin.mock.calls[0]![0] as Record<string, (this: unknown, options?: unknown) => void>
    const app = { $mpType: 'app' }
    const component = { $mpType: 'component', $scope: { route: 'pages/incorrect' } }
    hooks.onLaunch!.call(component, { path: 'wrong' }); hooks.onShow!.call(component, {})
    expect(f.tracker.queuedEvents()).toHaveLength(0)
    hooks.onLaunch!.call(app, { path: '/pages/home', query: { a: 1 }, scene: 1001 })
    hooks.onShow!.call(app, {})
    const page = { $mpType: 'page', $scope: { route: 'pages/home' }, $page: { fullPath: '/pages/home?x=1' } }
    hooks.onLoad!.call(page, { p: 2 }); hooks.onShow!.call(page)
    expect(f.tracker.queuedEvents().map(event => event.eventType)).toEqual(['VISIT', 'PAGE'])
    expect(f.tracker.queuedEvents()[0]).toMatchObject({ path: 'pages/home', query: 'a=1', appChannel: 'scn:1001' })
    expect(f.tracker.queuedEvents()[1]).toMatchObject({ path: 'pages/home', query: 'p=2', referralPage: target === 'mp-weixin' ? 'scn:1001' : 'scn:alip_1001' })
    const success = vi.fn()
    const options = { title: 'Updated', success }
    f.interceptors.get('setNavigationBarTitle')!.invoke!(options)
    options.success()
    expect(success).toHaveBeenCalledOnce()
    f.tracker.track('with_title')
    expect(f.tracker.queuedEvents().at(-1)!.title).toBe('Updated')
    hooks.onHide!.call(component)
    expect(f.sent).toHaveLength(0)
  })
  it('uses launch and enter fallbacks without overriding an authoritative hot entry', async () => {
    const f = miniHost(target); f.init(); await f.tracker.whenReady()
    const mixin = vi.fn()
    const fallback = { getLaunchOptionsSync: () => ({ path: '/pages/launch', query: { cold: 1 }, scene: 1001 }), getEnterOptionsSync: vi.fn(() => ({} as Record<string, unknown>)) }
    installUniAppLifecycle({ mixin }, f.tracker, { miniprogram: target, host: { ...f.host, ...fallback } })
    const hooks = mixin.mock.calls[0]![0] as Record<string, (this: unknown, options?: unknown) => void>
    const app = { $mpType: 'app' }
    hooks.onLaunch!.call(app); hooks.onShow!.call(app)
    expect(f.tracker.queuedEvents()[0]).toMatchObject({ path: 'pages/launch', query: 'cold=1' })
    fallback.getEnterOptionsSync.mockReturnValue({ path: '/pages/fallback', scene: 1002 })
    hooks.onHide!.call(app)
    hooks.onShow!.call(app, { query: { extra: 'yes' }, referrerInfo: { appId: 'referrer' } })
    expect(f.tracker.queuedEvents().at(-1)).toMatchObject({ path: 'pages/fallback', query: 'extra=yes', referralPage: 'referrer', appChannel: 'scn:1002' })
    hooks.onShow!.call(app, { path: '/pages/hot', query: { hot: true }, scene: 1003 })
    expect(f.tracker.queuedEvents().at(-1)).toMatchObject({ path: 'pages/hot', query: 'hot=true', appChannel: 'scn:1003' })
    const page = { $mpType: 'page', $page: { fullPath: '/pages/hot?unsafe=1' } }
    hooks.onLoad!.call(page, { good: 1, $taroTimestamp: 2 }); hooks.onShow!.call(page)
    expect(f.tracker.queuedEvents().at(-1)!.query).toBe('good=1')
  })
  it('can retry public initialization after an invalid appId without installing hooks or writing storage', async () => {
    vi.resetModules()
    const f = miniHost(target)
    vi.stubGlobal('uni', f.host)
    const { gdp } = await import('../../index.js')
    const mixin = vi.fn()
    let tracker: TrackerRuntime | undefined
    gdp('registerPlugins', [{ name: 'capture', install: value => { tracker = value } }])
    expect(gdp('init', 'account', 'source', { uniVue: { mixin }, appId: 'wrong' })).toBe(false)
    expect(mixin).not.toHaveBeenCalled()
    expect(f.host.setStorageSync).not.toHaveBeenCalled()
    expect(gdp('init', 'account', 'source', { uniVue: { mixin }, appId: f.appId })).toBe(true)
    expect(await tracker!.whenReady()).toBe(true)
    expect(mixin).toHaveBeenCalledOnce()
    expect(gdp('init', 'account', 'source', { uniVue: { mixin }, appId: f.appId })).toBe(false)
    expect(gdp('track', 'early')).toBe(true)
  })
})

describe('mini entry sanitation', () => {
  it('merges safe extra data without mutating native objects, dropping internal and invalid query values', () => {
    const query = { a: 1, b: false, nested: {}, wxShoppingListScene: 1007, $taroTimestamp: 2, circle: 'gdpCircleRoomCollectUrl', get broken() { throw new Error() } }
    const options = { path: '/pages/home', query, scene: 1001, referrerInfo: { appId: 'external', extraData: '{"a":2,"extra":"yes"}' } }
    expect(appEntrySnapshot(options, 'mp-weixin')).toEqual({ path: 'pages/home', query: 'a=1&b=false&extra=yes', scene: '1007', referralPage: 'external' })
    expect(query).toHaveProperty('wxShoppingListScene', 1007)
    expect(appEntrySnapshot({ query: 'a=1&bad=%ff&b=false&empty', scene: Infinity, referrerInfo: { extraData: 'invalid' } }, 'mp-alipay')).toEqual({ path: null, query: 'a=1&b=false&empty=', scene: null, referralPage: null })
  })
})
